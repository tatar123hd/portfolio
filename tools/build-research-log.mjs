// Builds assets/js/data/research-log.js from the research system's track-record.csv.
// Usage: node tools/build-research-log.mjs "<path to track-record.csv>"
// Only public fields are kept: no decisions, prices, FX or holdings.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// RFC 4180: quoted fields, doubled quotes, commas and newlines inside quotes.
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += ch;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim() !== ''));
}

function isoDate(s) {
  const t = s.trim();
  if (/^\d{4}-\d{2}-\d{2}$/.test(t)) return t;
  const [d, m, y] = t.split('/').map(Number);
  return `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}

// Site copy rule: no em dashes. The CSV elsewhere uses " - ", so match that.
const plain = (s) => s.replace(/\s*—\s*/g, ' - ').trim();

function oneLine(s, max = 160) {
  let t = plain(s.split(';')[0]);
  if (t.length <= max) return t;
  t = t.slice(0, max);
  return t.slice(0, t.lastIndexOf(' ')).replace(/[\s,.-]+$/, '') + '…';
}

export function buildLog(csvText) {
  const [header, ...rows] = parseCsv(csvText.replace(/^﻿/, ''));
  const col = (name) => header.indexOf(name);
  const weeks = new Map();
  for (const r of rows) {
    const week = isoDate(r[col('Date')]);
    if (!weeks.has(week)) weeks.set(week, []);
    weeks.get(week).push({
      ticker: r[col('Ticker')],
      asset: r[col('Asset')],
      type: r[col('Type')],
      call: r[col('Call')],
      horizon: r[col('Horizon')],
      conf: r[col('Conf')],
      why: oneLine(r[col('Why')]),
      risk: plain(r[col('Risks')].split(' / ')[0]),
      kill: plain(r[col('Kill')]),
    });
  }
  return [...weeks.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([week, calls]) => {
      const [, m, d] = week.split('-').map(Number);
      return { week, label: `${d} ${MONTHS[m - 1]}`, calls };
    });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = process.argv[2];
  if (!src) throw new Error('Pass the path to track-record.csv');
  const log = buildLog(readFileSync(src, 'utf8'));
  const out = new URL('../assets/js/data/research-log.js', import.meta.url);
  writeFileSync(out, `// Generated by tools/build-research-log.mjs. Do not edit by hand.\nexport const RESEARCH_LOG = ${JSON.stringify(log, null, 2)};\n`);
  console.log(`Wrote ${log.length} weeks to ${fileURLToPath(out)}`);
}
